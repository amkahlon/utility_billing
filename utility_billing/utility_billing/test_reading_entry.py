"""Increment 47: the Reading Entry screen, smart (AMI) meters read by the meter data system (MDM), and files from the mobile
reading app and the MDM.

User, 2026-11-24: readings "may be entered by a user, may be uploaded from a csv or text file generated by a mobile meter reading
app, or may come from MDM in case if a society also has installed some smart meters, and meter reading fields should be editable
only other than AMI/smart meters"; and "in case if a smart meter is mute, then its reading will be captured by meter reader".

House N 2308 (spec test case 1): the meter stood at 3,641 in September; 3,905 in October is 264 units."""

import frappe
from frappe.tests import IntegrationTestCase

from utility_billing.api import guard, v1
from utility_billing.install import create_default_exception_codes, create_default_utilities
from utility_billing.utility_billing import reading_entry, readings
from utility_billing.utility_billing.testing import BILLING_OFFICER, make_users

SOC = "TST-RDE"
READER = "tst.meter.reader@example.com"
API_USER = "tst.api.mdm@example.com"
MONTH = "2026-10-01"
BY_HAND = "Smart meter not communicating: read by hand."


class IntegrationTestReadingEntry(IntegrationTestCase):
	def setUp(self):
		create_default_utilities()
		create_default_exception_codes()
		make_users()
		if not frappe.db.exists("User", READER):
			u = frappe.get_doc({"doctype": "User", "email": READER, "first_name": "Reader", "send_welcome_email": 0})
			u.insert(ignore_permissions=True)
			u.add_roles("Meter Reader")
		if not frappe.db.exists("Society", SOC):
			frappe.get_doc({"doctype": "Society", "society_name": "Reading Entry Test Society", "short_name": SOC}).insert()
		if not frappe.db.exists("Consumer Category", "Electricity-TST RDE"):
			frappe.get_doc({"doctype": "Consumer Category", "category_name": "TST RDE", "utility": "Electricity"}).insert()
		self.consumer = frappe.get_doc({"doctype": "Consumer", "consumer_name": "Entry Consumer"}).insert().name
		# three accounts: an ordinary meter, a smart meter, and a smart net-metering meter
		self.plain = self.account("TST-RDE-M1", "N 2308", 3641)
		self.smart = self.account("TST-RDE-S1", "N 2309", 1000, smart_meter=1)
		self.solar = self.account("TST-RDE-S2", "N 2310", 500, smart_meter=1, meter_type="Net Metering")
		self.cycle = f"{SOC}-Electricity-{MONTH[:7]}"
		frappe.get_doc({"doctype": "Reading Cycle", "society": SOC, "utility": "Electricity", "billing_month": MONTH}).insert()
		readings.create_reading_sheet(self.cycle)

	def tearDown(self):
		frappe.set_user("Administrator")
		frappe.db.rollback()

	def account(self, serial, house, start, **meter):
		m = frappe.get_doc({"doctype": "Meter", "serial_no": serial, "society": SOC, "utility": "Electricity", "digits": 5, "multiplier": 1, **meter}).insert().name
		prop = frappe.get_doc({"doctype": "Property", "society": SOC, "property_no": house}).insert().name
		return frappe.get_doc({"doctype": "Connection", "society": SOC, "property": prop, "consumer": self.consumer, "utility": "Electricity",
		                       "consumer_category": "Electricity-TST RDE", "status": "Active",
		                       "meters": [{"meter": m, "installed_on": "2026-01-01", "start_reading": start}]}).insert().name

	def reading(self, conn):
		return frappe.get_doc("Meter Reading", {"reading_cycle": self.cycle, "connection": conn})

	def upload(self, text, source, name="readings.csv"):
		file = frappe.get_doc({"doctype": "File", "file_name": name, "content": text, "is_private": 1}).insert()
		return readings.upload_readings(self.cycle, file.file_url, source)

	# ---- smart meters
	def test_a_smart_meters_reading_isnt_typed_unless_the_meter_is_mute(self):
		r = self.reading(self.smart)
		self.assertEqual((r.smart_meter, r.smart_meter_mute, self.reading(self.plain).smart_meter), (1, 0, 0))
		r.present_reading, r.reading_date = 1300, "2026-10-05"
		self.assertRaisesRegex(frappe.ValidationError, "is a smart meter: its reading comes from the MDM", r.save)
		# an exception code (why it wasn't read) is still taken: the meter is then estimated like any other
		r = self.reading(self.smart)
		r.exception_code = "No Access"
		r.save()
		self.assertEqual(r.status, "Pending")
		# mute: the meter reader's reading is taken, marked, and always goes to a reviewer
		r.exception_code, r.smart_meter_mute, r.present_reading, r.reading_date = None, 1, 1300, "2026-10-05"
		r.save()
		self.assertEqual((r.units, r.status, r.source, r.checks), (300, "Flagged", "Office", BY_HAND))
		frappe.set_user(BILLING_OFFICER)
		readings.approve_reading(r.name, "The reader's photo shows 1300")
		frappe.set_user("Administrator")
		r.reload()
		self.assertEqual((r.status, r.units), ("Approved", 300))

	def test_an_ordinary_meter_is_typed_as_before_and_takes_nothing_from_the_mdm(self):
		r = self.reading(self.plain)
		r.present_reading, r.reading_date = 3905, "2026-10-05"
		r.save()
		self.assertEqual((r.units, r.status, r.smart_meter), (264, "Valid", 0))
		out = self.upload(f"Reference No,Present Reading,Reading Date\n{self.plain},3910,2026-10-06\n", "MDM")
		self.assertEqual(out["updated"], 0)
		self.assertIn("isn't a smart meter", out["errors"][0]["error"])
		self.assertEqual(self.reading(self.plain).present_reading, 3905)

	def test_a_reviewer_cant_correct_a_smart_meters_reading_by_hand(self):
		self.upload(f"Meter No,Reading,Reading Date\nTST-RDE-S1,1300,2026-10-05\n", "MDM")
		r = self.reading(self.smart)
		self.assertEqual((r.units, r.source, r.status), (300, "MDM", "Valid"))
		frappe.set_user(BILLING_OFFICER)
		self.assertRaisesRegex(frappe.ValidationError, "isn't corrected by hand", readings.correct_reading, r.name, 1310, "A typing slip")
		readings.request_reread(r.name, "The MDM figure looks high")
		frappe.set_user("Administrator")
		self.assertEqual(self.reading(self.smart).status, "Re-read Requested")

	# ---- files
	def test_the_mdms_file_gives_smart_meters_their_readings_by_meter_number(self):
		out = self.upload("Meter No,Reading,Reading Date,Export Reading,MDI\n"
		                  "tst-rde s1,1300,2026-10-05,,4.2\n"      # the number as the app compares it: no case, spaces or dashes
		                  "TST-RDE-S2,800,2026-10-05,120,\n"
		                  "NO-SUCH-METER,10,2026-10-05,,\n", "MDM")
		self.assertEqual((out["updated"], [e["reference_no"] for e in out["errors"]]), (2, ["NO-SUCH-METER"]))
		a, b = self.reading(self.smart), self.reading(self.solar)
		self.assertEqual((a.units, a.source, a.status, a.mdi_kw, a.smart_meter_mute), (300, "MDM", "Valid", 4.2, 0))
		self.assertEqual((b.units, b.export_units, b.source), (300, 120, "MDM"))
		# a later MDM file for the same cycle replaces the MDM's own reading
		self.upload("Meter No,Reading,Reading Date\nTST-RDE-S1,1320,2026-10-06\n", "MDM")
		self.assertEqual(self.reading(self.smart).units, 320)

	def test_the_mobile_apps_text_file_reads_ordinary_meters_and_mute_smart_meters(self):
		text = ("Reference No|Present Reading|Reading Date|Mute\n"
		        f"{self.plain}|3905|2026-10-05|\n"
		        f"{self.smart}|1300|2026-10-05|\n"       # a smart meter, not marked mute: refused
		        f"{self.solar}|800|2026-10-05|yes\n")    # a smart meter the reader found mute
		out = self.upload(text, "Mobile", name="mobile-readings.txt")
		self.assertEqual((out["updated"], [e["row"] for e in out["errors"]]), (2, [3]))
		self.assertIn("is a smart meter", out["errors"][0]["error"])
		p, s = self.reading(self.plain), self.reading(self.solar)
		self.assertEqual((p.units, p.source, p.status), (264, "Mobile", "Valid"))
		self.assertEqual((s.units, s.source, s.status, s.smart_meter_mute), (300, "Mobile", "Flagged", 1))
		self.assertIn(BY_HAND, s.checks)
		self.assertEqual(self.reading(self.smart).status, "Pending")
		# tabs and semicolons part the columns too
		self.assertEqual(readings._read_text("a\tb\n1\t2\n"), [["a", "b"], ["1", "2"]])
		self.assertEqual(readings._read_text(b"\xef\xbb\xbfa;b\r\n1;2\r\n\r\n"), [["a", "b"], ["1", "2"]])
		self.assertRaisesRegex(frappe.ValidationError, "Say where the file is from", self.upload, text, "Fax")

	def test_a_hand_reading_isnt_overwritten_when_the_mdm_reports_later(self):
		r = self.reading(self.smart)
		r.smart_meter_mute, r.present_reading, r.reading_date = 1, 1300, "2026-10-05"
		r.save()
		out = self.upload("Meter No,Reading,Reading Date\nTST-RDE-S1,1295,2026-10-06\n", "MDM")
		self.assertEqual(out["updated"], 0)
		self.assertIn("the hand reading is kept", out["errors"][0]["error"])
		r.reload()
		self.assertEqual((r.present_reading, r.source, r.status, r.smart_meter_mute), (1300, "Office", "Flagged", 1))
		self.assertIn("The MDM then sent 1295.0", r.checks)
		self.assertIn(BY_HAND, r.checks)

	# ---- the API
	def test_the_mdm_sends_readings_through_the_api(self):
		if not frappe.db.exists("User", API_USER):
			u = frappe.get_doc({"doctype": "User", "email": API_USER, "first_name": "mdm", "send_welcome_email": 0, "user_type": "System User"})
			u.append("roles", {"role": "API Integration"})
			u.insert(ignore_permissions=True)
		client = frappe.get_doc({"doctype": "API Client", "client_name": "TST MDM", "user": API_USER, "enabled": 1, "rate_limit": 100,
		                         "scope_account_read": 1, "societies": [{"society": SOC}]}).insert()
		rows = [{"meter_no": "TST-RDE-S1", "reading": 1300, "reading_date": "2026-10-05", "mdi": 3.5},
		        {"meter_no": "TST-RDE-S2", "reading": 800, "reading_date": "2026-10-05", "export_reading": 120},
		        {"meter_no": "TST-RDE-M1", "reading": 3905, "reading_date": "2026-10-05"},
		        {"meter_no": "NO-SUCH-METER", "reading": 5}, {"meter_no": "TST-RDE-S1"}]

		def call(**kw):
			frappe.set_user(API_USER)
			try:
				return v1.post_meter_readings(**kw)
			finally:
				frappe.set_user("Administrator")

		self.assertRaises(frappe.PermissionError, call, readings=rows, idempotency_key="M0")  # the client hasn't the scope
		client.scope_reading_write = 1
		client.save()
		self.assertRaises(frappe.ValidationError, call, readings=rows)  # a write needs an Idempotency-Key
		out = call(readings=frappe.as_json(rows), idempotency_key="M1")
		self.assertEqual((out["accepted"], out["rejected"]), (2, 3))
		self.assertEqual([(x["meter_no"], x["status"], x["units"]) for x in out["readings"]], [("TST-RDE-S1", "Valid", 300.0), ("TST-RDE-S2", "Valid", 300.0)])
		reasons = {x["meter_no"]: x["reason"] for x in out["errors"]}
		self.assertIn("isn't a smart meter", reasons["TST-RDE-M1"])
		self.assertIn("No open reading cycle", reasons["NO-SUCH-METER"])
		a = self.reading(self.smart)
		self.assertEqual((a.source, a.mdi_kw, a.owner != API_USER), ("MDM", 3.5, True))
		self.assertEqual(self.reading(self.solar).export_units, 120)
		self.assertEqual(self.reading(self.plain).status, "Pending")
		self.assertEqual(call(readings=frappe.as_json(rows), idempotency_key="M1"), out)  # a retry gives the same answer, nothing read twice
		# a society the client isn't given
		client.set("societies", [])
		client.all_societies = 0
		client.append("societies", {"society": frappe.db.get_value("Society", {"name": ["!=", SOC]}, "name")})
		client.save()
		refused = call(readings=rows[:1], idempotency_key="M2")
		self.assertEqual((refused["accepted"], refused["rejected"]), (0, 1))
		self.assertIn("reading.write", guard.SCOPES)
		self.assertIn("utility_billing.api.v1.post_meter_readings", guard.REGISTRY)

	# ---- the Reading Entry screen
	def test_the_screen_lists_the_cycles_accounts_with_what_is_typed(self):
		d = reading_entry.get_sheet(society=SOC)
		self.assertEqual((d["cycle"], d["status"], d["can_write"], d["more"], len(d["rows"])), (self.cycle, "Open", True, False, 3))
		self.assertEqual(d["totals"], {"records": 3, "entered": 0, "exceptions": 0, "not_read": 0, "smart": 2, "import_units": 0.0, "export_units": 0.0})
		row = next(r for r in d["rows"] if r.connection == self.plain)
		self.assertEqual((row.meter, row.previous_reading, row.multiplier, row.digits, row.smart_meter, row.entered, row.category, row.status),
		                 ("TST-RDE-M1", 3641, 1, 5, 0, False, "TST RDE", "Pending"))
		self.assertIn("No Access", [c["name"] for c in d["codes"]])
		self.assertEqual([r.connection for r in reading_entry.get_sheet(cycle=self.cycle, search="RDE-S2")["rows"]], [self.solar])
		self.assertEqual(reading_entry.get_sheet(cycle=self.cycle, show="exceptions")["rows"], [])

	def test_rows_are_saved_as_their_readings_and_the_others_still_save(self):
		name = lambda conn: self.reading(conn).name  # noqa: E731
		out = reading_entry.save_rows(self.cycle, frappe.as_json([
			{"name": name(self.plain), "present_reading": "3905", "mdi_kw": "", "reading_date": "", "exception_code": ""},
			{"name": name(self.smart), "present_reading": "1300", "reading_date": "2026-10-05", "exception_code": "", "smart_meter_mute": 0},
			{"name": name(self.solar), "present_reading": "800", "present_export_reading": "120", "reading_date": "2026-10-05", "exception_code": "",
			 "smart_meter_mute": 1},
		]))
		self.assertEqual((out["saved"], out["failed"]), (2, 1))
		by = {x["name"]: x for x in out["rows"]}
		p, s, n = by[name(self.plain)], by[name(self.smart)], by[name(self.solar)]
		self.assertEqual((p["ok"], p["units"], p["status"], p["reading_date"], p["entered"], p["source"]), (True, 264, "Valid", frappe.utils.nowdate(), True, "Office"))
		self.assertEqual((s["ok"], "is a smart meter" in s["error"]), (False, True))
		self.assertEqual((n["ok"], n["units"], n["export_units"], n["status"], n["smart_meter_mute"]), (True, 300, 120, "Flagged", 1))
		self.assertEqual(out["totals"], {"records": 3, "entered": 2, "exceptions": 1, "not_read": 0, "smart": 2, "import_units": 564.0, "export_units": 120.0})
		self.assertEqual([r.connection for r in reading_entry.get_sheet(cycle=self.cycle, show="exceptions")["rows"]], [self.solar])
		self.assertEqual([r.connection for r in reading_entry.get_sheet(cycle=self.cycle, show="to_enter")["rows"]], [self.smart])
		# nothing typed anew: nothing saved; a reason for not reading clears the reading; an emptied cell takes it back
		same = reading_entry.save_rows(self.cycle, [{"name": name(self.plain), "present_reading": "3905", "reading_date": frappe.utils.nowdate(), "exception_code": ""}])
		self.assertEqual((same["saved"], same["rows"][0]["saved"]), (0, False))
		code = reading_entry.save_rows(self.cycle, [{"name": name(self.plain), "present_reading": "3905", "exception_code": "No Access"}])["rows"][0]
		self.assertEqual((code["exception_code"], code["status"], code["units"], code["reading_date"]), ("No Access", "Pending", 0, ""))
		back = reading_entry.save_rows(self.cycle, [{"name": name(self.plain), "present_reading": "3905", "exception_code": ""}])["rows"][0]
		self.assertEqual((back["units"], back["status"]), (264, "Valid"))
		cleared = reading_entry.save_rows(self.cycle, [{"name": name(self.plain), "present_reading": "", "exception_code": ""}])["rows"][0]
		self.assertEqual((cleared["status"], cleared["entered"], cleared["units"]), ("Pending", False, 0))

	def test_who_may_type_and_a_closed_cycle(self):
		frappe.set_user(READER)
		d = reading_entry.get_sheet(cycle=self.cycle)
		self.assertTrue(d["can_write"])
		out = reading_entry.save_rows(self.cycle, [{"name": self.reading(self.plain).name, "present_reading": "3905", "exception_code": ""}])
		self.assertEqual(out["saved"], 1)
		frappe.set_user("Administrator")
		other = frappe.get_doc({"doctype": "Reading Cycle", "society": SOC, "utility": "Electricity", "billing_month": "2026-11-01"}).insert()
		self.assertFalse(reading_entry.save_rows(other.name, [{"name": self.reading(self.plain).name, "present_reading": "1"}])["rows"][0]["ok"])
		for conn in (self.smart, self.solar):
			r = self.reading(conn)
			r.exception_code = "No Access"
			r.save()
		readings.estimate_unread(self.cycle)
		readings.close_cycle(self.cycle)
		self.assertFalse(reading_entry.get_sheet(cycle=self.cycle)["can_write"])
		self.assertRaisesRegex(frappe.ValidationError, "closed", reading_entry.save_rows, self.cycle, [])
